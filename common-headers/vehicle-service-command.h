//------------------------------------------------------------------------------
//
//      Сервисные команды вагона (меню вагона)
//
//      Команды передаются по уже существующему каналу
//      STYPE_SEND_VEHICLE_CONTROL_COMMAND с зарезервированными ID
//      в диапазоне 0xF000..0xF0FF. Это позволяет не менять сетевой
//      протокол и не затрагивать интерфейсы SDK.
//
//      Значения ID должны совпадать на клиенте (viewer) и сервере
//      (simulator), поэтому оба места используют этот заголовок.
//
//------------------------------------------------------------------------------

#ifndef     VEHICLE_SERVICE_COMMAND_H
#define     VEHICLE_SERVICE_COMMAND_H

#include    <cstdint>

namespace vehicle_service
{

//------------------------------------------------------------------------------
/// Действия меню вагона
//------------------------------------------------------------------------------
enum Action : std::uint16_t
{
    ParkingBrake    = 0xF001,   ///< Ручной (стояночный) тормоз, value: 0/1

    HoseConnectFwd  = 0xF010,   ///< Соединить рукав с передней стороны
    HoseHangFwd     = 0xF011,   ///< Повесить рукав на крюк (передняя сторона)
    HoseConnectBwd  = 0xF012,   ///< Соединить рукав с задней стороны
    HoseHangBwd     = 0xF013,   ///< Повесить рукав на крюк (задняя сторона)

    EndValveFwd     = 0xF020,   ///< Концевой кран, передняя сторона, value: 0/1
    EndValveBwd     = 0xF021,   ///< Концевой кран, задняя сторона, value: 0/1

    UncoupleFwd     = 0xF030,   ///< Рычаг расцепки, передняя сторона
    UncoupleBwd     = 0xF031,   ///< Рычаг расцепки, задняя сторона

    DoorsOpen       = 0xF040,   ///< Открыть пассажирские двери состава, value: 1
    DoorsClose      = 0xF041,   ///< Закрыть пассажирские двери состава, value: 1

    ChockFwd        = 0xF050,   ///< Тормозной башмак, передняя тележка, value: 0/1
    ChockBwd        = 0xF051    ///< Тормозной башмак, задняя тележка, value: 0/1
};

//------------------------------------------------------------------------------
/// Проверка принадлежности ID к сервисным командам вагона
//------------------------------------------------------------------------------
inline bool isServiceCommand(std::uint16_t id)
{
    return (id >= 0xF000) && (id <= 0xF0FF);
}

//------------------------------------------------------------------------------
/// Команды дверями относятся ко всему составу, а не к отдельному вагону
//------------------------------------------------------------------------------
inline bool isTrainDoorCommand(std::uint16_t id)
{
    return (id == DoorsOpen) || (id == DoorsClose);
}

} // namespace vehicle_service

#endif // VEHICLE_SERVICE_COMMAND_H
