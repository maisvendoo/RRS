#ifndef GPX_READER_H
#define GPX_READER_H

#include <string>
#include <vector>

namespace osm
{

//------------------------------------------------------------------------------
/// Точка GPX (трек-поинт)
//------------------------------------------------------------------------------
struct GpxPoint
{
    double lat = 0.0;
    double lon = 0.0;
    double ele = 0.0;       // метры, 0 если нет <ele>
    bool has_ele = false;
};

//------------------------------------------------------------------------------
/// Трек GPX
//------------------------------------------------------------------------------
struct GpxTrack
{
    std::string name;
    std::vector<GpxPoint> points;
};

//------------------------------------------------------------------------------
/// Прочитать GPX 1.0/1.1 (trk/trkseg/trkpt, rte/rtept)
//------------------------------------------------------------------------------
bool parse_gpx(const std::string& path, std::vector<GpxTrack>& out,
               std::string* error);

} // namespace osm

#endif // GPX_READER_H
