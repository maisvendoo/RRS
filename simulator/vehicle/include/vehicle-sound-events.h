//------------------------------------------------------------------------------
//
//      Vehicle sound events (мост физика -> аудиосистема)
//      ТЗ "Продвинутая пространственная и физическая аудиосистема"
//
//      Звук - результат физического события: сила удара ползуна,
//      контакт гребня, удар/разрыв сцепки, скрежет после схода, дуга
//      токоприёмника, поток песка, боксование. Событие несёт мировую
//      позицию (из profile_point ПЕ) и интенсивность 0..1 (громкость
//      и спектр выбирает аудиосистема по типу и силе).
//
//------------------------------------------------------------------------------

#ifndef     VEHICLE_SOUND_EVENTS_H
#define     VEHICLE_SOUND_EVENTS_H

#include    <cstddef>
#include <vector>

//------------------------------------------------------------------------------
/// Физические звуковые события ПЕ
//------------------------------------------------------------------------------
enum class SoundEventType : unsigned char
{
    FlatImpact = 0,     ///< Удар ползуна о рельс (частота = обороты)
    FlangeContact = 1,  ///< Скрежет гребня о рельс
    CouplerImpact = 2,  ///< Удар в сцепке (выбор зазора)
    CouplerBreak = 3,   ///< Разрыв сцепки
    DerailmentScrape = 4,///< Скрежет сошедшей ПЕ о шпалы
    PantographArc = 5,  ///< Дуга токоприёмника
    SandFlow = 6,       ///< Шум песка под колёсами
    WheelSlip = 7,      ///< Визг боксования/юза
    JointImpact = 8,    ///< Стук на стыке пути
    BrakeSqueal = 9     ///< Свист тормозных колодок
};

/// Звуковое событие
struct SoundEvent
{
    SoundEventType type = SoundEventType::FlatImpact;

    double x = 0.0;             ///< Мировая позиция, м
    double y = 0.0;
    double z = 0.0;

    double intensity = 0.0;     ///< 0..1 (сила/громкость)
    double rate_hz = 0.0;       ///< Частота повтора (удары ползуна и т.п.)

    size_t vehicle_idx = 0;     ///< Индекс ПЕ-источника
};

#endif // VEHICLE_SOUND_EVENTS_H
