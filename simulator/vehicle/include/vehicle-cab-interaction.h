//
//      Cab interaction (универсальная система интерактивной кабины)
//      ТЗ "Взаимодействие с элементами кабины"
//
//      Ядро реестра интерактивных органов управления: каждый элемент
//      имеет идентификатор (ссылку на орган управления конфига кабины),
//      имя и подсказку (режим Alt), состояние включён/выключен/среднее.
//      Дополнительно: тип элемента (Toggle/Button/Lever/Valve/Gauge),
//      непрерывное состояние 0..1 (MinState..MaxState), имя анимации
//      (anim_name), звук (sound_id), флаги interactable/highlight и
//      имя модели для сопоставления с мешем (raycast-пикинг вьювера).
//      Взаимодействие (мышь/клавиши) и подсветка - во вьювере;
//      физические связи - через существующие IOController/устройства.
//
//------------------------------------------------------------------------------

#ifndef     VEHICLE_CAB_INTERACTION_H
#define     VEHICLE_CAB_INTERACTION_H

#include    <QString>

#include    <cstddef>
#include <vector>

//------------------------------------------------------------------------------
/// Тип интерактивного элемента кабины
//------------------------------------------------------------------------------
enum class CabElementType
{
    Toggle = 0,     ///< Тумблер/переключатель: два положения
    Button,         ///< Кнопка: мгновенное действие
    Lever,          ///< Рычаг (кран машиниста, реверс): непрерывный ход
    Valve,          ///< Вентиль/кран: непрерывный ход
    Gauge           ///< Прибор: только индикация (не интерактивен)
};

//------------------------------------------------------------------------------
/// Реестр интерактивных элементов кабины
//------------------------------------------------------------------------------
class CabInteractionRegistry
{
public:

    /// Элемент управления
    struct Item
    {
        int id = 0;                 ///< ID органа управления (из конфига)
        QString name = "";          ///< Имя для подсказки Alt
        QString hint = "";          ///< Описание ("что делает")
        bool is_toggle = true;      ///< Переключатель или кнопка (совместимость)
        bool state = false;         ///< Текущее состояние (для подсветки)

        //--- Расширение ядра (ТЗ "Взаимодействие с кабиной") ---

        CabElementType type = CabElementType::Toggle;  ///< Тип элемента
        double value = 0.0;         ///< Непрерывное состояние (MinState..MaxState)
        double min_state = 0.0;     ///< Нижняя граница состояния
        double max_state = 1.0;     ///< Верхняя граница состояния
        bool continuous = false;    ///< Непрерывное состояние (рычаг/вентиль/прибор)
        bool interactable = true;   ///< Доступен для взаимодействия (клик)
        bool highlight = false;     ///< Подсветка при наведении (задаёт вьювер)
        int sound_id = -1;          ///< Звук по событию (-1 - нет)
        QString anim_name = "";     ///< Имя анимации/параметра (позиция анимации)
        QString model_name = "";    ///< Имя меша (сопоставление с элементом)
    };

    CabInteractionRegistry() = default;

    /// Загрузка секций [CabElement] конфига ПЕ: ключи ControlID/Name/
    /// Hint/IsToggle + Type/MinState/MaxState/SoundID/AnimName/
    /// Continuous/ModelName/Interactable
    void loadConfig(QString cfg_path);

    /// Число элементов
    std::size_t count() const;

    /// Элемент по индексу (для обхода вьювером)
    const Item& getItem(std::size_t index) const;

    /// Поиск по ID органа управления (-1 - не найден)
    int findByControlId(int control_id) const;

    /// Поиск по имени меша (-1 - не найден): вьювер сопоставляет
    /// объект модели (raycast-пикинг) с элементом кабины. Приоритет -
    /// явный ключ ModelName, затем имя элемента Name
    int findByModelName(const QString& model_name) const;

    /// Задать состояние элемента (клик игрока): дискретное вкл/выкл
    void setState(std::size_t index, bool state);

    /// Задать непрерывное состояние (перетаскивание рычага/вентиля):
    /// зажимается в MinState..MaxState, дискретное состояние
    /// синхронизируется по середине диапазона
    void setValue(std::size_t index, double value);

    /// Режим подсказок включён (Alt удерживается - показывает вьювер)
    bool hints_mode = false;

private:

    std::vector<Item> items_;
};

#endif // VEHICLE_CAB_INTERACTION_H
