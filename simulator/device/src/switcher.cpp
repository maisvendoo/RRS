#include "switcher.h"

//------------------------------------------------------------------------------
//
//------------------------------------------------------------------------------
Switcher::Switcher(std::uint16_t num_positions)
{
    setNumPositions(num_positions);
}

//------------------------------------------------------------------------------
//
//------------------------------------------------------------------------------
void Switcher::setNumPositions(std::uint16_t num_positions)
{
    if (num_positions > 1)
        num_states = num_positions;
}

//------------------------------------------------------------------------------
//
//------------------------------------------------------------------------------
void Switcher::setInitPosition(std::uint16_t position)
{
    if (position >= num_states)
    {
        position = (position > num_states) ? 0 : (num_states - 1);
    }
    state = position;
}

//------------------------------------------------------------------------------
//
//------------------------------------------------------------------------------
void Switcher::setPosition(std::uint16_t position)
{
    if (position >= num_states)
    {
        position = (position > num_states) ? 0 : (num_states - 1);
    }

    if (state == position)
    {
        return;
    }

    state = position;
    switch_sound.play();
}

//------------------------------------------------------------------------------
//
//------------------------------------------------------------------------------
void Switcher::incPos()
{
    if (state < (num_states - 1))
    {
        ++state;
        switch_sound.play();
    }
}

//------------------------------------------------------------------------------
//
//------------------------------------------------------------------------------
void Switcher::decPos()
{
    if (state)
    {
        --state;
        switch_sound.play();
    }
}

//------------------------------------------------------------------------------
//
//------------------------------------------------------------------------------
std::uint16_t Switcher::getNumPositions() const
{
    return num_states;
}

//------------------------------------------------------------------------------
//
//------------------------------------------------------------------------------
std::uint16_t Switcher::getPosition() const
{
    return state;
}

//------------------------------------------------------------------------------
//
//------------------------------------------------------------------------------
float Switcher::getHandlePosition() const
{
    return static_cast<float>(state) / static_cast<float>(num_states - 1);
}

//------------------------------------------------------------------------------
//
//------------------------------------------------------------------------------
bool Switcher::isSwitched(std::uint16_t pos) const
{
    return pos == state;
}

//------------------------------------------------------------------------------
//
//------------------------------------------------------------------------------
sound_state_t Switcher::getSoundState(size_t idx) const
{
    (void) idx;
    return switch_sound;
}

//------------------------------------------------------------------------------
//
//------------------------------------------------------------------------------
float Switcher::getSoundSignal(size_t idx) const
{
    (void) idx;
    return switch_sound.createSoundSignal();
}
